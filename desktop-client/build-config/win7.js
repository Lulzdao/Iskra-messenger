// Сборка для Windows 7 и 8.1.
//
// Electron 22.3.27 — последняя версия, работающая на этих системах: начиная с 23 поддержка Win7/8.1
// в Electron убрана. Поэтому версия здесь ЗАМОРОЖЕНА и поднимать её нельзя, пока такие машины
