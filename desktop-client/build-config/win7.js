// запускает именно её, и несовместимость с Win7 всплывает сразу у разработчика, а не через месяц
// у сотрудника. Это и есть замена «отдельной ветки под Win7» из первоначального плана.
//
// Сборка рассчитана на самую старую поддерживаемую систему, поэтому запускается и на Windows 10 —
// проверки версии ОС при установке здесь намеренно нет (в отличие от win10.js).

